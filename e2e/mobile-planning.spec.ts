test('supplies can be chosen before planning and only query the resulting route', async ({ page }) => {
  const requests: string[][] = []
  await page.route('**/api/pois/nearby', (route) => {
    requests.push(route.request().postDataJSON().categories)
    return route.fulfill({ json: { pois: [], truncated: false, corridorM: 500, source: { regionId: 'ch', snapshotAt: '2026-08-14T20:21:03Z', importedAt: '2026-10-18T12:00:00Z' } } })
  })
  await page.getByLabel('Verpflegung auf der Karte').check()
  await expect(page.getByText('Wird nach der Routenberechnung angezeigt.')).toBeVisible()
  const supplies = page.getByRole('region', { name: 'Verpflegung', exact: true })
  await supplies.getByRole('button', { name: 'Lebensmittel', exact: true }).click()
  expect(requests).toEqual([])
  await page.route('**/api/places/search?**', (route) => route.fulfill({ json: { results: [{ label: 'Bern, Schweiz', coordinate: [7.4474, 46.948] }] } }))
  await page.getByRole('combobox', { name: 'Startort suchen' }).fill('Bern')
  await page.getByRole('option', { name: 'Bern, Schweiz', exact: true }).click()
  await page.getByRole('button', { name: 'Route planen', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Routenname', exact: true })).toBeVisible()
  await expect.poll(() => requests.length).toBe(1)
  expect(requests[0]).toEqual(['water', 'food'])
  await page.getByRole('button', { name: 'Planungsmenü öffnen' }).click()
  await page.getByRole('button', { name: 'Orte und Zwischenstopps ansehen' }).click()
  await expect(page.getByRole('dialog', { name: 'Versorgung entlang der Route' })).toBeVisible()
})

