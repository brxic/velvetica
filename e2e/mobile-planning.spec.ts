test('mobile form remains reachable on small, landscape and keyboard-sized viewports', async ({ page }, info) => {
  test.skip(info.project.name !== 'mobile', 'Mobile viewport cases only')
  await page.route('**/api/places/search?**', (route) => route.fulfill({ json: { results: [{ label: 'Bern, Schweiz', coordinate: [7.4474, 46.948] }] } }))
  await page.getByRole('combobox', { name: 'Startort suchen' }).fill('Bern')
  await page.getByRole('option', { name: 'Bern, Schweiz', exact: true }).click()
  for (const viewport of [{ width: 390, height: 667 }, { width: 800, height: 390 }, { width: 390, height: 420 }]) {
    await page.setViewportSize(viewport)
    const panel = page.locator('#planner-controls')
    const box = (await panel.boundingBox())!
    expect(box.y).toBeGreaterThan(70)
    expect(box.y + box.height).toBeLessThanOrEqual(viewport.height + 1)
    await expect(page.getByRole('combobox', { name: 'Startort suchen' })).toHaveValue('Bern, Schweiz')
    await page.getByRole('button', { name: 'Erweiterte Wünsche' }).click()
    const preference = page.getByRole('combobox', { name: 'Untergrund' })
    await preference.scrollIntoViewIfNeeded()
    await expect(preference).toBeVisible()
    const head = await page.locator('.planner-sheet-head').boundingBox()
    expect(head!.y).toBeCloseTo(box.y + 1, 0)
    if (process.env.VELVETIA_LIVE_MAP === '1') await page.waitForLoadState('networkidle')
    await page.screenshot({ path: info.outputPath(`planning-${viewport.width}-${viewport.height}.png`) })
    await page.getByRole('button', { name: 'Erweiterte Wünsche' }).click()
    await page.getByRole('button', { name: 'Karte', exact: true }).click()
    const collapsed = (await panel.boundingBox())!
    expect(collapsed.height).toBeLessThanOrEqual(66)
    await page.getByRole('button', { name: 'Öffnen', exact: true }).click()
  }
})
