test('mobile sheet minimises by drag, keeps inputs and scroll position, and leaves the map usable', async ({ page }, info) => {
  test.skip(info.project.name !== 'mobile', 'Mobile sheet only')
  const panel = page.locator('#planner-controls')
  const scroll = page.locator('.planner-scroll')
  await page.getByRole('button', { name: 'One-Way', exact: true }).click()
  await scroll.evaluate((el) => { el.scrollTop = 180 })
  const originalScroll = await scroll.evaluate((el) => el.scrollTop)
  const head = page.locator('.planner-sheet-head')
  const before = await head.boundingBox()
  await scroll.evaluate((el) => { el.scrollTop = 240 })
  expect((await head.boundingBox())!.y).toBe(before!.y)
  expect(await page.locator('.planner-scroll-frame').evaluate((el) => getComputedStyle(el).paddingTop)).toBe('16px')
  const handle = page.getByRole('button', { name: 'Planung minimieren' })
  const bounds = (await handle.boundingBox())!
  await page.mouse.move(bounds.x + 40, bounds.y + 30)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 40, bounds.y + 130, { steps: 6 })
  await page.mouse.up()
  await expect(panel).toHaveClass(/is-peek/)
  expect((await panel.boundingBox())!.height).toBeLessThanOrEqual(66)
  await expect(scroll).toHaveAttribute('inert', '')
  const canvas = page.locator('.maplibregl-canvas')
  await expect(canvas).toBeVisible()
  await page.mouse.move(210, 220)
  await page.mouse.wheel(0, -150)
  await expect(panel).toHaveClass(/is-peek/)
  await page.screenshot({ path: info.outputPath('planning-map-peek.png') })
  await page.getByRole('button', { name: 'Planung aufklappen' }).click()
  await expect(panel).not.toHaveClass(/is-peek/)
  expect(await scroll.evaluate((el) => el.scrollTop)).toBeGreaterThanOrEqual(originalScroll)
  await expect(page.getByRole('combobox', { name: 'Zielort suchen' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Karte', exact: true }).click()
  await expect(panel).toHaveClass(/is-peek/)
  await page.getByRole('button', { name: 'Öffnen', exact: true }).click()
  await expect(panel).not.toHaveClass(/is-peek/)
  // Also exercise native touch pointer capture, not just mouse emulation.
  const touch = await page.context().newCDPSession(page)
  const grip = (await handle.boundingBox())!
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: grip.x + 40, y: grip.y + 25 }] })
  for (const distance of [15, 35, 65, 90]) await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: grip.x + 40, y: grip.y + 25 + distance }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(panel).toHaveClass(/is-peek/)
  await touch.detach()
  await page.getByRole('button', { name: 'Öffnen', exact: true }).click()
  // A desktop resize must not leave the form inert after minimising on mobile.
  await page.getByRole('button', { name: 'Karte', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(scroll).not.toHaveAttribute('inert', '')
  await expect(page.getByRole('button', { name: 'One-Way', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

