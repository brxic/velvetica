test('real worker caches the shell and .mjs; offline saving stays local and does not cover route controls', async ({ page, context, request }, info) => {
  const manifest = await (await request.get('/manifest.webmanifest')).json()
  expect(manifest.display).toBe('standalone')
  expect(manifest.icons.some((icon: { purpose?: string }) => icon.purpose === 'maskable')).toBe(true)
  const workerResponse = await request.get('http://127.0.0.1:3026/sw.js')
  expect(workerResponse.headers()['cache-control']).toContain('no-store')
  expect(workerResponse.headers()['service-worker-allowed']).toBe('/')
  await ready(page)
  await page.reload() // Navigation now passes through the actual active worker.
  await page.evaluate(async () => { await fetch('/maplibre/maplibre-gl-worker.mjs') })
  await page.getByLabel('GPX-Datei auswählen').setInputFiles('test-fixtures/bern-import.gpx')
  await page.getByRole('button', { name: 'Hinweis schliessen' }).click()
  await context.setOffline(true)
  const status = page.getByRole('complementary', { name: 'App-Status' })
  await expect(status).toContainText('Offline')
  await page.getByRole('button', { name: 'Route speichern', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Routenzusammenfassung' })).toContainText('Lokal · Cloud ausstehend')
  const save = page.getByRole('button', { name: 'Änderungen speichern', exact: true })
  await expect.poll(() => save.evaluate((element) => { const rect = element.getBoundingClientRect(); return element.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)) })).toBe(true)
  const assets = await page.evaluate(async () => (await caches.open('velvetia-shell-v2')).keys().then((keys) => keys.map((key) => new URL(key.url).pathname)))
  expect(assets).toContain('/maplibre/maplibre-gl-worker.mjs')
  await page.getByRole('button', { name: 'Hinweis schliessen' }).click()
  await page.screenshot({ path: `test-results/p2-offline-${info.project.name}.png` })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Anmelden', exact: true })).toBeVisible()
  await expect(page.getByRole('complementary', { name: 'App-Status' })).toContainText('Offline')
  await context.setOffline(false)
  await expect(page.getByRole('complementary', { name: 'App-Status' })).toContainText('Netzwerk wieder verbunden')
  // Offline cold starts must not expose account-scoped drafts before identity
  // can be verified. Reconnection now explicitly offers local recovery.
  const recovery = page.getByRole('dialog', { name: 'Entwurf wiederherstellen' })
  await expect(recovery).toBeVisible()
  await recovery.getByRole('button', { name: 'Wiederherstellen', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Routenname', exact: true })).toHaveValue('Bern Testfahrt')
  await page.getByRole('button', { name: 'Status schliessen' }).click()
  await expect(page.getByRole('complementary', { name: 'App-Status' })).not.toBeVisible()
})

test('successful share HTML is never available offline, including an old v1 cache entry', async ({ page, context }) => {
  await ready(page)
  await page.goto('/share/pwa-fixture')
  await expect(page.getByRole('heading', { name: 'Freigabe-Testinhalt' })).toBeVisible()
  await page.evaluate(async () => { const old = await caches.open('velvetia-shell-v1'); await old.put('/share/pwa-fixture', new Response('<h1>Alter Freigabeinhalt</h1>', { headers: { 'Content-Type': 'text/html' } })) })
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Du bist offline.' })).toBeVisible()
  await expect(page.getByText('Alter Freigabeinhalt')).not.toBeVisible()
})

test('update waits for saved draft and other tabs, then activates and reloads only on request', async ({ page, context, request }) => {
  await ready(page)
  await page.getByLabel('GPX-Datei auswählen').setInputFiles('test-fixtures/bern-import.gpx')
  await page.getByRole('button', { name: 'Hinweis schliessen' }).click()
  const name = page.getByRole('textbox', { name: 'Routenname' })
  await name.fill('P2 Entwurf bleibt erhalten')
  await request.post('/__qa/worker-revision?value=updated')
  await page.evaluate(async () => { await (await navigator.serviceWorker.ready).update() })
  const update = page.getByRole('button', { name: 'Jetzt aktualisieren' })
  await expect(update).toBeVisible()
  await update.click()
  await expect(page.getByRole('complementary', { name: 'App-Status' })).toContainText('Speichere oder beende')
  await expect(name).toHaveValue('P2 Entwurf bleibt erhalten')
  await page.getByRole('button', { name: 'Route speichern', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Routenzusammenfassung' })).toContainText('Lokal · Cloud ausstehend')
  const another = await context.newPage(); await another.goto('/')
  await update.click()
  await expect(page.getByRole('complementary', { name: 'App-Status' })).toContainText('weitere Velvetia-Tabs')
  await expect(name).toHaveValue('P2 Entwurf bleibt erhalten')
  await another.close()
  await Promise.all([page.waitForEvent('load'), update.click()])
  await expect(page.getByRole('button', { name: 'Jetzt aktualisieren' })).not.toBeVisible()
  await page.getByRole('dialog', { name: 'Entwurf wiederherstellen' }).getByRole('button', { name: 'Wiederherstellen', exact: true }).click()
  await expect(name).toHaveValue('P2 Entwurf bleibt erhalten')
  await page.getByRole('button', { name: /^Meine Routen/ }).click()
  await expect(page.getByRole('button', { name: /^P2 Entwurf bleibt erhalten Rennrad/ })).toBeVisible()
})
